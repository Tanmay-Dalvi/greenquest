import React from 'react';
import { Sparkles, ShieldCheck, WifiOff, Server } from 'lucide-react';

interface OfflineBannerProps {
  fallbackUsed: boolean;
  providerName: string;
}

export const OfflineBanner: React.FC<OfflineBannerProps> = ({
  fallbackUsed,
  providerName,
}) => {
  if (!fallbackUsed) {
    return (
      <div className="bg-forest-900/40 border border-forest-800/60 rounded-xl px-3 py-2 text-xs flex items-center justify-between text-forest-800">
        <span className="flex items-center space-x-1.5 font-medium">
          <Sparkles className="w-3.5 h-3.5 text-amber-500" />
          <span>Generated by open-weight AI ({providerName})</span>
        </span>
        <span className="flex items-center space-x-1 text-sage-600 font-semibold text-[11px]">
          <ShieldCheck className="w-3.5 h-3.5 text-sage-500" />
          <span>Safety Audited</span>
        </span>
      </div>
    );
  }

  // Client-side PWA fallback (no connection to backend)
  if (providerName === 'client-offline') {
    return (
      <div className="bg-amber-50 border border-amber-200/80 rounded-xl p-3 text-xs text-forest-900 shadow-sm">
        <div className="flex items-start space-x-2">
          <WifiOff className="w-4 h-4 text-amber-600 mt-0.5 shrink-0" />
          <div>
            <p className="font-semibold text-amber-900">
              In-Browser Offline Mode Active
            </p>
            <p className="text-amber-800/90 text-[11px] mt-0.5 leading-relaxed">
              Generated locally in your browser without connecting to the backend. 100% offline-capable.
            </p>
          </div>
        </div>
      </div>
    );
  }

  // Live backend deterministic rule engine (e.g. Render cloud or configured fallback)
  if (providerName === 'fallback') {
    return (
      <div className="bg-cream-200/60 border border-sage-300 rounded-xl p-3 text-xs text-forest-900 shadow-sm">
        <div className="flex items-start space-x-2">
          <Server className="w-4 h-4 text-forest-700 mt-0.5 shrink-0" />
          <div>
            <p className="font-semibold text-forest-900">
              Deterministic Nature Engine Active (Live Backend)
            </p>
            <p className="text-forest-800/90 text-[11px] mt-0.5 leading-relaxed">
              Generated by the live backend using its deterministic rule engine (not Gemma). Reliable, instant, and privacy-preserving.
            </p>
          </div>
        </div>
      </div>
    );
  }

  // Other providers when fallback was triggered (e.g. Ollama or Hosted timeout)
  return (
    <div className="bg-amber-50 border border-amber-200/80 rounded-xl p-3 text-xs text-forest-900 shadow-sm">
      <div className="flex items-start space-x-2">
        <Sparkles className="w-4 h-4 text-amber-600 mt-0.5 shrink-0" />
        <div>
          <p className="font-semibold text-amber-900">
            Deterministic Safety Fallback Active
          </p>
          <p className="text-amber-800/90 text-[11px] mt-0.5 leading-relaxed">
            Inference provider ({providerName}) was unavailable or encountered a timeout; generated safely by the backend rule engine.
          </p>
        </div>
      </div>
    </div>
  );
};

